package topic01basics;

// Every Java program lives inside a class
public class Hello {

    // main is the entry point: where the JVM starts running your program.
    public static void main(String[] args) {

        // println prints text, then moves to a new line.
        System.out.println("Hello, Java!");

        // print prints text and stays on the same line.
        System.out.println("No new line here. ");
        System.out.println("Now we continue");
    }
}